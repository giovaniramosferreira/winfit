import assert from 'node:assert/strict'
import { createWorkoutStorage, safeWorkoutState } from '../src/lib/workoutStorage'
const empty = { profile: null, plan: null, archivedPlans: [], sessions: [], activeSession: null, prs: [] }
const data = new Map<string, string>()
const port = { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => { data.set(key, value) }, removeItem: (key: string) => { data.delete(key) } }
data.set('winfit-v1', '{bad')
const bad = createWorkoutStorage(port)
assert.equal(bad.getItem('winfit-v1'), null)
assert.equal(bad.health().blocked, true)
bad.setItem('winfit-v1', JSON.stringify({ state: empty }))
assert.equal(data.get('winfit-v1'), '{bad')
assert.equal(bad.original(), '{bad')
const quota = createWorkoutStorage({ ...port, setItem: () => { throw Error('quota') } })
assert.doesNotThrow(() => quota.setItem('winfit-v1', JSON.stringify({ state: empty })))
assert.match(quota.health().error!, /salvar/)
assert.equal(bad.resetGuard(), true)
assert.equal(bad.health().blocked, false)
assert.equal(data.has('winfit-v1'), false)
const safe = safeWorkoutState({ ...empty, resetAll: 'oops', logSet: 'oops', lastSetUndo: { dangerous: true }, seed: 'seed', watchToken: 'WF-AAAA', draft: { step: 1 } })
assert.equal('resetAll' in safe, false)
assert.equal('logSet' in safe, false)
assert.equal(safe.lastSetUndo, null)
assert.equal(safe.seed, 'seed')
data.set('winfit-v1', JSON.stringify({ state: { ...empty, resetAll: 'bad' }, version: 0 }))
const valid = createWorkoutStorage(port)
assert.equal(JSON.parse(valid.getItem('winfit-v1')!).state.resetAll, undefined)
const unavailable = createWorkoutStorage(null)
unavailable.setItem('winfit-v1', '{}')
assert.ok(unavailable.health().error)
console.log('Workout storage corruption guard, action whitelist, quota visibility and explicit reset OK')
